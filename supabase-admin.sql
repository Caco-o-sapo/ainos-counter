create or replace function public.audit_ainos_note_change()
returns trigger
language plpgsql security definer set search_path = ''
as $$
declare
  v_action text;
  v_target public.ainos_notes%rowtype;
  v_details jsonb;
begin
  if tg_op = 'INSERT' then
    v_target := new;
    v_action := 'note_created';
    v_details := jsonb_build_object('after', jsonb_build_object(
      'data', new.data, 'texto', new.texto, 'dia_bom', new.dia_bom, 'categoria', new.categoria
    ));
    perform public.record_ainos_admin_log(v_action, new.id, new.texto, v_details);
    return new;
  elsif tg_op = 'UPDATE' then
    if old.data is not distinct from new.data
       and old.texto is not distinct from new.texto
       and old.dia_bom is not distinct from new.dia_bom
       and old.categoria is not distinct from new.categoria then
      return new;
    end if;
    v_details := jsonb_build_object(
      'before', jsonb_build_object('data', old.data, 'texto', old.texto, 'dia_bom', old.dia_bom, 'categoria', old.categoria),
      'after', jsonb_build_object('data', new.data, 'texto', new.texto, 'dia_bom', new.dia_bom, 'categoria', new.categoria)
    );
    perform public.record_ainos_admin_log('note_updated', new.id, new.texto, v_details);
    return new;
  else
    v_details := jsonb_build_object('before', jsonb_build_object(
      'data', old.data, 'texto', old.texto, 'dia_bom', old.dia_bom, 'categoria', old.categoria
    ));
    perform public.record_ainos_admin_log('note_deleted', old.id, old.texto, v_details);
    return old;
  end if;
end;
$$;
revoke all on function public.audit_ainos_note_change() from public, anon, authenticated;
drop trigger if exists ainos_notes_audit_trigger on public.ainos_notes;
create trigger ainos_notes_audit_trigger
  after insert or update or delete on public.ainos_notes
  for each row execute function public.audit_ainos_note_change();

create or replace function public.audit_ainos_comment_delete()
returns trigger
language plpgsql security definer set search_path = ''
as $$
begin
  perform public.record_ainos_admin_log(
    'comment_deleted',
    old.note_id,
    coalesce(old.nickname, 'Anônimo') || ': ' || old.body,
    jsonb_build_object('comment_id', old.id, 'nickname', old.nickname, 'body', old.body)
  );
  return old;
end;
$$;
