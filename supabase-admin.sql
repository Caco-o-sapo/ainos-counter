create table if not exists public.ainos_notes (
  id text primary key check (char_length(id) between 1 and 100),
  data date not null,
  texto text not null check (char_length(texto) between 1 and 2000),
  dia_bom boolean not null default false,
  categoria text null check (categoria is null or categoria in ('work','games','health','social','daily','other')),
  position integer not null default 0,
  created_at timestamptz not null default now(),
  updated_at timestamptz not null default now()
);
create index if not exists ainos_notes_date_position_idx
  on public.ainos_notes (data desc, position asc, created_at desc);

create table if not exists public.ainos_admin_allowlist (
  email text primary key check (email = lower(email) and char_length(email) between 3 and 320),
  created_at timestamptz not null default now()
);
alter table public.ainos_admin_allowlist
  add column if not exists is_owner boolean not null default false;

create table if not exists public.ainos_admins (
  user_id uuid primary key references auth.users(id) on delete cascade,
  email text not null,
  created_at timestamptz not null default now()
);
alter table public.ainos_admins
  add column if not exists is_owner boolean not null default false;
alter table public.ainos_admins
  add column if not exists display_name text not null default '';

create table if not exists public.ainos_admin_logs (
  id bigint generated by default as identity primary key,
  actor_id uuid null references auth.users(id) on delete set null,
  actor_email text not null,
  actor_label text not null,
  action text not null check (action in (
    'note_created','note_updated','note_deleted',
    'admin_added','admin_removed','admin_name_changed',
    'comment_deleted','owner_designated'
  )),
  target_id text not null,
  target_summary text not null default '',
  details jsonb not null default '{}'::jsonb,
  created_at timestamptz not null default now()
);
create index if not exists ainos_admin_logs_created_idx
  on public.ainos_admin_logs (created_at desc);

alter table public.ainos_notes enable row level security;
alter table public.ainos_admin_allowlist enable row level security;
alter table public.ainos_admins enable row level security;
alter table public.ainos_admin_logs enable row level security;

create or replace function public.is_ainos_admin()
returns boolean
language sql stable security definer set search_path = ''
as $$
  select exists (
    select 1 from public.ainos_admins
    where user_id = (select auth.uid())
  );
$$;

create or replace function public.is_ainos_owner()
returns boolean
language sql stable security definer set search_path = ''
as $$
  select exists (
    select 1 from public.ainos_admins
    where user_id = (select auth.uid()) and is_owner
  );
$$;

create or replace function public.record_ainos_admin_log(
  p_action text,
  p_target_id text,
  p_summary text,
  p_details jsonb default '{}'::jsonb
)
returns void
language plpgsql security definer set search_path = ''
as $$
declare
  v_actor uuid := (select auth.uid());
  v_email text;
  v_label text;
begin
  select a.email, coalesce(nullif(a.display_name, ''), a.email)
    into v_email, v_label
    from public.ainos_admins a
    where a.user_id = v_actor;

  insert into public.ainos_admin_logs
    (actor_id, actor_email, actor_label, action, target_id, target_summary, details)
  values (
    v_actor,
    coalesce(v_email, (select auth.jwt() ->> 'email'), 'Supabase SQL Editor'),
    coalesce(v_label, v_email, (select auth.jwt() ->> 'email'), 'Supabase SQL Editor'),
    p_action,
    left(coalesce(p_target_id, 'unknown'), 100),
    left(coalesce(p_summary, ''), 500),
    coalesce(p_details, '{}'::jsonb)
  );
end;
$$;
revoke all on function public.record_ainos_admin_log(text,text,text,jsonb) from public, anon, authenticated;

create or replace function public.claim_ainos_admin_access()
returns boolean
language plpgsql security definer set search_path = ''
as $$
declare
  v_email text;
  v_confirmed_at timestamptz;
  v_is_owner boolean;
  v_name text;
begin
  select lower(u.email), u.email_confirmed_at,
         coalesce(nullif(u.raw_user_meta_data ->> 'full_name', ''), split_part(lower(u.email), '@', 1))
    into v_email, v_confirmed_at, v_name
    from auth.users u
    where u.id = (select auth.uid());

  if v_email is null or v_confirmed_at is null then return false; end if;

  select a.is_owner into v_is_owner
    from public.ainos_admin_allowlist a
    where a.email = v_email;

  if not found then return false; end if;

  insert into public.ainos_admins (user_id, email, is_owner, display_name)
  values ((select auth.uid()), v_email, coalesce(v_is_owner, false), v_name)
  on conflict (user_id) do update
    set email = excluded.email,
        is_owner = excluded.is_owner;

  return true;
end;
$$;

create or replace function public.get_my_ainos_admin_profile()
returns table(display_name text, is_owner boolean)
language sql stable security definer set search_path = ''
as $$
  select a.display_name, a.is_owner
  from public.ainos_admins a
  where a.user_id = (select auth.uid());
$$;

create or replace function public.set_my_ainos_admin_name(p_name text)
returns boolean
language plpgsql security definer set search_path = ''
as $$
declare
  v_name text := trim(coalesce(p_name, ''));
  v_old text;
begin
  if not public.is_ainos_admin() then raise exception 'not_authorized'; end if;
  if char_length(v_name) < 2 or char_length(v_name) > 40 then raise exception 'invalid_name'; end if;

  select display_name into v_old from public.ainos_admins
    where user_id = (select auth.uid());
  if v_old is distinct from v_name then
    update public.ainos_admins set display_name = v_name
      where user_id = (select auth.uid());
    perform public.record_ainos_admin_log(
      'admin_name_changed',
      (select auth.uid())::text,
      v_name,
      jsonb_build_object('before', v_old, 'after', v_name)
    );
  end if;
  return true;
end;
$$;

create or replace function public.set_ainos_admin_email(p_email text, p_allowed boolean)
returns boolean
language plpgsql security definer set search_path = ''
as $$
declare
  v_email text := lower(trim(coalesce(p_email, '')));
begin
  if not public.is_ainos_admin() then raise exception 'not_authorized'; end if;
  if v_email = '' or char_length(v_email) > 320 or position('@' in v_email) < 2 then
    raise exception 'invalid_email';
  end if;

  if p_allowed then
    if not exists (select 1 from public.ainos_admin_allowlist where email = v_email) then
      insert into public.ainos_admin_allowlist(email) values (v_email);
      perform public.record_ainos_admin_log('admin_added', v_email, 'E-mail autorizado: ' || v_email, '{}'::jsonb);
    end if;
  else
    if exists (select 1 from public.ainos_admin_allowlist where email = v_email and is_owner)
       or exists (select 1 from public.ainos_admins where email = v_email and is_owner) then
      raise exception 'cannot_remove_owner';
    end if;
    if exists (
      select 1 from public.ainos_admins
      where email = v_email and user_id = (select auth.uid())
    ) and (select count(*) from public.ainos_admins) <= 1 then
      raise exception 'cannot_remove_last_admin';
    end if;

    if exists (select 1 from public.ainos_admin_allowlist where email = v_email) then
      delete from public.ainos_admin_allowlist where email = v_email;
      delete from public.ainos_admins where email = v_email;
      perform public.record_ainos_admin_log('admin_removed', v_email, 'Acesso removido: ' || v_email, '{}'::jsonb);
    end if;
  end if;
  return true;
end;
$$;

