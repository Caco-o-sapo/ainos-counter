-- Ainos Watch: comentários e reações públicos por ocorrência.
-- Execute este arquivo uma vez no Supabase > SQL Editor.
-- RLS limita formato e tamanho dos dados; o site usa somente a publishable key.

create table if not exists public.ainos_comments (
  id bigint generated by default as identity primary key,
  note_id text not null check (char_length(note_id) between 1 and 100),
  nickname text not null default 'Anônimo' check (char_length(nickname) between 1 and 30),
  body text not null check (char_length(body) between 1 and 500),
  created_at timestamptz not null default now()
);

create table if not exists public.ainos_reactions (
  id bigint generated by default as identity primary key,
  note_id text not null check (char_length(note_id) between 1 and 100),
  visitor_id text not null check (char_length(visitor_id) between 8 and 80),
  emoji text not null check (emoji in ('😂', '😭', '💀', '😮', '❤️')),
  created_at timestamptz not null default now(),
  constraint ainos_reactions_once_per_visitor unique (note_id, visitor_id, emoji)
);

create index if not exists ainos_comments_note_created_idx
  on public.ainos_comments (note_id, created_at desc);
create index if not exists ainos_reactions_note_idx
  on public.ainos_reactions (note_id);

alter table public.ainos_comments enable row level security;
alter table public.ainos_reactions enable row level security;

grant select, insert on public.ainos_comments to anon, authenticated;
grant select, insert on public.ainos_reactions to anon, authenticated;
grant usage, select on sequence public.ainos_comments_id_seq to anon, authenticated;
grant usage, select on sequence public.ainos_reactions_id_seq to anon, authenticated;

drop policy if exists "Anyone can read Ainos comments" on public.ainos_comments;
create policy "Anyone can read Ainos comments"
  on public.ainos_comments for select to anon, authenticated
  using (true);

drop policy if exists "Anyone can add bounded Ainos comments" on public.ainos_comments;
create policy "Anyone can add bounded Ainos comments"
  on public.ainos_comments for insert to anon, authenticated
  with check (
    char_length(note_id) between 1 and 100
    and char_length(nickname) between 1 and 30
    and char_length(body) between 1 and 500
  );

drop policy if exists "Anyone can read Ainos reactions" on public.ainos_reactions;
create policy "Anyone can read Ainos reactions"
  on public.ainos_reactions for select to anon, authenticated
  using (true);

drop policy if exists "Anyone can add valid Ainos reactions" on public.ainos_reactions;
create policy "Anyone can add valid Ainos reactions"
  on public.ainos_reactions for insert to anon, authenticated
  with check (
    char_length(note_id) between 1 and 100
    and char_length(visitor_id) between 8 and 80
    and emoji in ('😂', '😭', '💀', '😮', '❤️')
  );
